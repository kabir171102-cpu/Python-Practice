marks = int(input("Enter the marks :"))
if marks >= 40:
    print("Pass- 1st divison")
elif marks >= 30:
    print("Pass- 2nd divison")
elif marks >= 20:
    print("Pass- 3rd division")
else:
    print("Fail")

