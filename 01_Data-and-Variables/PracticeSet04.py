# 1- Celsius to Fohrenheit
# ===========================================================================================
c = float(input("Enter Celsius: "))
f = (9 / 5) * c + 32
print("Fohrenheit =", f)

# ===========================================================================================
# 2- Fohrenheit to Celcius
# ===========================================================================================

f = float(input("Enter Fohrenheit: "))
c = (5 / 9) * (f - 32)
print("Celsius =", c)

# ============================================================================================
# 3- Celsius to Kelvin
# ============================================================================================

c = float(input("Enter Celsius: "))
k = c + 273.15
print("Kelvin =", k)

# ============================================================================================
# 4- Kelvin to Celsius
# ============================================================================================

k = float(input("Enter Kelvin: "))
c = k - 273.15
print("Celsius = ", c)

# ============================================================================================
# 5- Fohrenheit to Kelvin
# ============================================================================================

f = float(input("Enter Fahrenheit: "))
k = (5 / 9) * (f - 32) + 273.15
print("Kelvin =", k)

# ============================================================================================
# 6- Kelvin to Fohrenheit
# ============================================================================================

k = float(input("Enter Kelvin: "))
f = (9 / 5) * (k - 273.15) + 32
print("Fohrenheit =", f)

