# Question 6- Print the elements of the following list using a loop.
#                [1, 4, 9, 16, 25, 36, 49, 64, 81, 100]
# =======================================================================================

num = 1
while num <= 10:
    print(num**2)
    num += 1

# =======
# Or-
# =======

nums = [1, 4, 9, 16, 25, 36, 49, 64, 81, 100]
idx = 0

while idx < len(nums):  # "Or"-  while idx <= len(nums)-1:
    print(nums[idx])
    idx += 1

# =======================================================================================
# Question 7- Search for a number x in this tuple using loop:
#               [1, 4, 9, 16, 25, 36, 49, 64, 81, 100]
# =======================================================================================

num = (1, 4, 9, 16, 25, 36, 49, 64, 81, 100)  # Tuple/

idx = 0
x = int(input("Enter X value :"))

while idx < len(num):
    if num[idx] == x:
        print("Found X value on Index =", idx)
    idx += 1

