# Question 2- Find X Value.
# =======================================================================================

nums = [1, 4, 9, 16, 25, 36, 49, 64, 81, 100]

i = 0
x = int(input("Enter X Value :"))

while i < len(nums):
    if nums[i] == x:
        print("Found X Value On Index", i)
        break
    else:
        print("Finding....", i)

    i += 1
print("End of Loop")

