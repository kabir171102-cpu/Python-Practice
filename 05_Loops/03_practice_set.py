# Quetion 1- Print the number 1 to 100.
# =======================================================================================

num = 1
while num <= 100:
    print(num)
    num += 1

# =======================================================================================
# Quetion 2- Print even numbers between 1 to 50.
# =======================================================================================

num = 1
while num <= 50:
    if num % 2 == 0:
        print(num)
    num += 1

# =======================================================================================
# Quetion 3- Print Odd numbers between 1 to 50.
# =======================================================================================

num = 1
while num <= 50:
    if num % 2 != 0:
        print(num)
    num += 1

# =======================================================================================
# Quetion 4- Take a number from user and print the table of that number.
# =======================================================================================

num = int(input("Enter The Number :"))
i = 1
while i <= 10:
    print(num, "x", i, "=", num * i)
    i += 1

# =======================================================================================
# Quetion 5- Print the sum Numbers between 1 to 100.
# =======================================================================================

total = 0

for i in range(1, 101):
    total = total + i

print(total)

# =======================================================================================
# Quetion 6- Print the numbers 1 to 50 who divided by 3.
# =======================================================================================

for i in range(3, 51, 3):
    print(i)

# =======================================================================================
# Quetion 7- Print Squares of number 1 to 10.
# =======================================================================================

for i in range(1, 11):
    print(i**2)

# =======================================================================================
# Quetion 8- Take a number from user and print their factorial(!).
# =======================================================================================

num = int(input("Enter Number :"))
factorial = 1
i = 1

while i <= num:
    factorial *= i
    i += 1
print("Factorial =", factorial)

# =======================================================================================
# Quetion 9- Take the numbers 1 to 100 and print those numbers who's divided by 5 and 7.
# =======================================================================================

for i in range(1, 101):
    if i % 5 == 0 and i % 7 == 0:
        print(i)

# =======================================================================================
# Question 10- Take 5 numbers from user and print sum of all numbers.
# =======================================================================================

total = 0
for i in range(5):
    num = int(input("Enter Number :"))
    total = total + num

print(total)

