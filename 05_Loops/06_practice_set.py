# Question 1- Print numbers from 100 to 1.
# =======================================================================================
# 'Using While"-
# =================

num = 100
while num >= 1:
    print(num)
    num -= 1

# =================
# "Using For"-
# =================

for i in range(100, 0, -1):
    print(i)

