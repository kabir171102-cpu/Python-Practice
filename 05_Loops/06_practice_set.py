# Question 8- Find the sum of all even numbers between 1 and 100.
# =======================================================================================

sum = 0

for i in range(1, 101):
    if i % 2 == 0:
        sum = sum + i
print("Total =", sum)

# ============
# Or-
# ============

total = 0
for i in range(2, 101, 2):
    total = total + i

print("Total =", total)

# =======================================================================================
# Question 9- Print all numbers between 1 and 100,
#  that are divisible by 3 but not divisible by 5.
# =======================================================================================

for i in range(1, 101):
    if i % 3 == 0 and i % 5 != 0:
        print(i)

