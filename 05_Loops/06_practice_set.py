# Question 2- Print the multiplication tables from 1 to 5.
# =======================================================================================

for i in range(1, 6):
    print(f"\nTable of {i}")

    for j in range(1, 11):
        print(f"{i} x {j} = {i * j}")

# =======================================================================================
# Question 3- Count how many even numbers are present between 1 and 100.
# =======================================================================================

count = 0
for i in range(1, 101):
    if i % 2 == 0:
        print(i)
        count += 1

print("Total Even =", count)

# =======================================================================================
# Question 4- Take 5 numbers from the user and find the largest number.
# =======================================================================================

num = [2, 3, 6, 17, 19, 91, 100]
largest = num[0]

for i in num:
    if i > largest:
        largest = i


print("Largest Number =", largest)

