# ======================================================================================
# """List Slicing"""
# ======================================================================================

marks = [85, 94, 76, 63, 48]

print(marks[1:4])  # [94, 76, 63]
print(marks[:4])  #  [85, 94, 76, 63]
print(marks[1:])  #   [94, 76, 63, 48]
print(marks[:])  #   [85, 94, 76, 63, 48]
print(marks[-5:-1])  # [85, 94, 76, 63]  # Not included [-1] idx No-
