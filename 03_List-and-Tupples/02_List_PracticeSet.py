# ========================================================================================
# Question 1-  Append
# ========================================================================================

my_list = [1, 4, 3]

my_list.append(2)
print(my_list)  # [1, 4, 3, 2]  "Add one element".

# ========================================================================================
# Question 2-  Ascending Order
# ========================================================================================

my_list = [1, 4, 3]

my_list.sort()
print(my_list)  # [1, 3, 4]  "In ascending order".

# ========================================================================================
# Question 3-  Descending Order
# ========================================================================================

my_list = [1, 4, 3]

my_list.sort(reverse=True)
print(my_list)  # [4, 3, 1]   "In Descending order".

# ========================================================================================
# Question 4-  Reverse
# ========================================================================================

my_list = [1, 4, 3]

my_list.reverse()
print(my_list)  # [3, 4, 1]    "Reverse".

# ========================================================================================
# Question 5-  Insert
# ========================================================================================

my_list = [1, 4, 3]

my_list.insert(2, 5)
print(my_list)  # [1, 4, 5, 3]   "On 2nd index, elemnt [5] add".

# ========================================================================================
# Question 6-  Remove
# ========================================================================================

my_list = [1, 4, 3]

my_list.remove(1)
print(my_list)  # [4, 3]   Remove index(1) Number.

# ========================================================================================
# Question 7-  Pop
# ========================================================================================

my_list = [1, 4, 3]

my_list.pop(2)
print(my_list)  # [1, 4]  Removes index(2) Number.

